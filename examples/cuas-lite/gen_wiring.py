#!/usr/bin/env python3
"""Regenerates docs/cuas-lite/wiring.md from assemblies/cuas-lite.toml (pin-to-pin tables per harness).

    python3 examples/cuas-lite/gen_wiring.py            # print the document
    python3 examples/cuas-lite/gen_wiring.py --check    # exit 1 if docs/cuas-lite/wiring.md differs (CI / pre-commit)

Everything in the tables comes from the assembly's [[wires]] (endpoints, pins, wire part = gauge, length) and the parts' connector pin names.
Colour and fuse columns are suggestions from the rules at the top of this file (COLOUR_OF, GROUPS): edit the rule, not the document.
Stdlib only; no napl import, so it runs anywhere.
"""

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASM = ROOT / "assemblies" / "cuas-lite.toml"
DOC = ROOT / "docs" / "cuas-lite" / "wiring.md"

# harness -> wire-name regexes (first match wins, in this order)
GROUPS = [
    (
        "1. Power rail (12 V in, fuse, bus, returns)",
        r"psu_cord|xt60_fuse|fuse_jetson|gnd_jetson|fuse_tmc_|gnd_tmc_",
    ),
    (
        "2. Weapon rail (key + E-stop + relay coil, relay contact, 5 V buck)",
        r"fuse_key|key_estop|estop_coil|coil_gnd|fuse_relay|relay_buck|gnd_buck|sense_",
    ),
    (
        "3. Flywheel MOSFETs (gate, drain, source, flyback, motor supply)",
        r"rail_fw_|fw_.*_drain|fb_q|q._source|gp12_gate|gate_q|gate_pulldown",
    ),
    ("4. Pusher servo", r"rail_servo|gp14_servo"),
    ("5. Hall sensors (pan, tilt)", r"hall_|jetson_5v_hall|v3_hp|v3_ht"),
    (
        "6. Pico to TMC2209 x 2 (pan, tilt: STEP/DIR/EN, UART, straps, VIO, motor leads)",
        r"^(pan|tilt)_|v3_en|v3_ms|vio_",
    ),
    ("7. Jetson USB and 5 V", r"usb_|jetson_5v_pico"),
]

FUSE_12V = r"psu_cord|xt60_fuse|fuse_|gnd_|key_estop|estop_coil|coil_gnd|relay_buck"
BUCK_5V = r"rail_|fw_.*_drain|fb_q|q._source"

# wire gauge note, colour per (wire-name regex, pin-name regex); first match wins. Pin name is the lower-cased name on either end.
COLOUR_OF = [
    (r".", r"^(gnd|-|v-|ground|dn\.2)$|gnd", "black"),
    (r"motor_leads", r"1a|a1|ph\.1", "black (A+)"),
    (r"motor_leads", r"1b|a2|ph\.2", "green (A-)"),
    (r"motor_leads", r"2a|b1|ph\.3", "red (B+)"),
    (r"motor_leads", r"2b|b2|ph\.4", "blue (B-)"),
    (r"step_dir", r"step", "green"),
    (r"step_dir", r"dir", "blue"),
    (r"step_dir", r"gnd", "black"),
    (r"^(pan|tilt)_en_", r".", "white"),
    (r"_uart_", r".", "violet"),
    (r"_ms[12]", r".", "grey"),
    (r"vio_|v3_", r".", "brown (3.3 V)"),
    (r"hall_.*out|hall_.*gp", r".", "yellow"),
    (r"usb_", r"vbus|5v", "red"),
    (r"usb_", r"d\+|dp", "green"),
    (r"usb_", r"d-|dm", "white"),
    (r"usb_", r"id", "grey"),
    (r"jetson_5v|rail_servo|hall_pan_to_tilt", r".", "orange (5 V)"),
    (r"rail_fw|fw_.*_drain|fb_q|q._source", r".", "orange (5 V rail)"),
    (r"gp12_gate|gate_q", r".", "white"),
    (r"gp14_servo", r".", "white"),
    (r"sense_", r".", "white"),
    (r"coil|key_estop|fuse_key|estop_coil", r".", "red/white (switched 12 V)"),
    (r"fuse_|psu_cord|xt60|relay_buck", r".", "red (12 V)"),
]


def load_parts():
    idx = {}
    for f in (ROOT / "parts").rglob("*.toml"):
        d = tomllib.loads(f.read_text())
        idx[d["id"]] = d
    return idx


def pin_name(part, pin):
    cid, _, num = pin.partition(".")
    for c in part.get("connectors", []):
        if c["id"] == cid:
            for p in c.get("pins", []):
                if str(p.get("number")) == num:
                    return p.get("name", pin)
    return pin


def gauge(part_id):
    m = re.search(r"awg-(\d+)", part_id)
    return f"{m.group(1)} AWG" if m else part_id


def colour(wire, names):
    for wre, pre, col in COLOUR_OF:
        if re.search(wre, wire) and any(re.search(pre, n.lower()) for n in names):
            return col
    return "-"


def fuse(wire):
    if re.search(r"psu_cord|xt60_fuse", wire):
        return "upstream of F1"
    if re.search(BUCK_5V, wire):
        return "F1 10 A upstream; buck current limit"
    if re.search(FUSE_12V, wire):
        return "F1 10 A"
    return "-"


def length_m(w, asm):
    ln = w.get("length")
    if isinstance(ln, dict):
        return f"{ln['value']:.2f}"
    if isinstance(ln, (int, float)):
        return f"{ln:.2f}"
    return "psu cord"


def main():
    asm = tomllib.loads(ASM.read_text())
    parts = load_parts()
    inst = {i["id"]: i for i in asm["instances"]}

    def end(ref, pins):
        i, _, port = ref.partition(".")
        part = parts[inst[i]["part"]]
        return [f"{i}.{pin_name(part, p)}" for p in pins], [
            pin_name(part, p) for p in pins
        ]

    out = []
    w_ = out.append
    w_("# cuas-lite wiring, pin to pin")
    w_("")
    w_(
        "GENERATED by `examples/cuas-lite/gen_wiring.py` from `assemblies/cuas-lite.toml` (the wires, pins and lengths) and the part files (pin names). Do not edit by hand: change the assembly or the rules"
    )
    w_(
        "at the top of the script and run it again. `python3 examples/cuas-lite/gen_wiring.py --check` fails if this file is stale. Firmware pins: `firmware/cuas-lite-rp2040/include/pins.h`."
    )
    w_("")
    w_(
        "Colour and fuse columns are suggestions (not modelled by the DRC). Lengths are the assembly's estimates in metres, without slack for strain relief. Pin names are the part files' connector pin"
    )
    w_(
        "names (the Pico row `GP12` is header pin 16, shown only as the name). Gauge is the wire part of the assembly."
    )
    w_("")
    w_(
        "Fuse F1 is the inline ATC blade holder between the XT60 and the bus. Fit a **10 A** blade (the listing ships 15-40 A: too big). Worst case at 12 V is about 5 A [est, from the part files' currents] (Jetson about 1.3 A, two steppers at 1.2 A RMS about 1 A, flywheels"
    )
    w_(
        "and servo through the buck about 2.5 A); 10 A protects the 18 AWG leads, not the 22 AWG key and coil branch (30 mA load). [est] If you want that branch protected too, add a 0.5 A inline fuse at the key; it is not in the BOM."
    )
    w_("")
    w_("## Weapon-rail interlock (hardware, independent of the Pico)")
    w_("")
    w_("```")
    w_("12 V bus (after F1)")
    w_("   |-------------------------------+")
    w_("   |                               |")
    w_("  KEY (COM-NO, rated 1 A)      relay contact SW (Songle SRD-12VDC-SL-C, 10 A)")
    w_("   |                               |")
    w_(
        "  E-STOP (NC contact)              +--> LM2596 buck (5 V) --+--> flywheel motors x2 (low side: MOSFET q1/q2, flyback d1/d2)"
    )
    w_("   |                                                        +--> pusher servo")
    w_("  relay COIL (30 mA) --> GND")
    w_("")
    w_(
        "key off OR E-stop pressed OR any broken wire in the coil loop  =>  coil dead  =>  contact open  =>  5 V weapon rail dead."
    )
    w_(
        "Sense taps (33k/10k dividers) read the key node and the E-stop node into GP11 / GP10 for the firmware; they do not control the rail."
    )
    w_("```")
    w_("")
    w_("Mermaid form of the same diagram:")
    w_("")
    w_("```mermaid")
    w_("flowchart LR")
    w_(
        "  BUS[12 V bus after F1] --> KEY[Key switch] --> ES[E-stop NC] --> COIL[Relay coil 30 mA] --> GND((GND))"
    )
    w_(
        "  BUS --> SW[Relay contact] --> BUCK[LM2596 5 V] --> FW[Flywheels via MOSFET q1/q2]"
    )
    w_("  BUCK --> SRV[Pusher servo]")
    w_("  KEY -. divider .-> GP11[Pico GP11]")
    w_("  ES -. divider .-> GP10[Pico GP10]")
    w_("```")
    w_("")
    seen = set()
    total_m = {}
    for title, rx in GROUPS:
        rows = []
        for w in asm["wires"]:
            if w["name"] in seen or not re.search(rx, w["name"]):
                continue
            seen.add(w["name"])
            fa, fn = end(w["from"], w.get("from_pins", []))
            ta, tn = end(w["to"], w.get("to_pins", []))
            n = max(len(fa), len(ta), 1)
            for k in range(n):
                a = fa[k] if k < len(fa) else w["from"]
                b = ta[k] if k < len(ta) else w["to"]
                names = [
                    x
                    for x in (
                        (fn[k] if k < len(fn) else ""),
                        (tn[k] if k < len(tn) else ""),
                    )
                    if x
                ]
                rows.append(
                    (
                        w["name"],
                        a,
                        b,
                        gauge(w["part"]),
                        colour(w["name"], names),
                        length_m(w, asm),
                        fuse(w["name"]),
                    )
                )
            total_m[w["part"]] = total_m.get(w["part"], 0) + (
                w["length"]["value"] if isinstance(w.get("length"), dict) else 0
            ) * max(1, w.get("conductors", 1))
        w_(f"## {title}")
        w_("")
        w_("| wire | from | to | gauge | colour | length m | fuse |")
        w_("|---|---|---|---|---|---|---|")
        for r in rows:
            w_("| " + " | ".join(r) + " |")
        w_("")
    rest = [w["name"] for w in asm["wires"] if w["name"] not in seen]
    if rest:
        w_("## Unassigned wires (add a group rule in the script)")
        w_("")
        w_(", ".join(rest))
        w_("")
    w_("## Wire totals (length x conductors, metres, from the assembly)")
    w_("")
    for k, v in sorted(total_m.items()):
        w_(f"- {gauge(k)}: {v:.1f} m")
    w_("")
    text = "\n".join(out)
    if "--check" in sys.argv:
        ok = DOC.exists() and DOC.read_text() == text
        sys.stderr.write(
            "wiring.md is up to date\n"
            if ok
            else "wiring.md is STALE: run examples/cuas-lite/gen_wiring.py\n"
        )
        return 0 if ok else 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
