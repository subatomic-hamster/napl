"""Builds assemblies/skydio.toml through the design API: the Holybro X500 V2 (assemblies/x500v2.toml) plus a nose-mounted Intel RealSense D435i
(depth camera + `rangefinder` device), a Raspberry Pi 5 companion computer stacked over the Pixhawk, and a Pololu D24V50F5 5 V regulator for them.

    python examples/skydio/build_design.py [out.toml]      # default assemblies/skydio.toml; run from the repo root with the project venv

Every edit is one `Design` call (the same ops as the MCP `design_*` tools and the viewer); the DRC delta of each is printed. Needs no kernel.
The result is committed as assemblies/skydio.toml (comments are not kept by `Design.save`; the header below is added back)."""

import math
import sys
from pathlib import Path

from napl.design import Design

REPO = Path(__file__).resolve().parents[2]
CAM_UP_DEG = 10.0  # the camera looks this far above the airframe's x axis: the quad pitches nose down ~7-9 deg at 4-5 m/s, this keeps the view level

# D435i pose (root = bottom plate frame, x forward, z up). The part frame is +z = viewing direction, +x = image up (right-handed: +y = image right),
# so body z -> airframe +x and body x -> airframe +z is R = Ry(-90 deg) Rx(180 deg); the upward tilt adds Ry(-tilt) on the left (fixed-axis rpy).
# Rear-face centre: 6 mm ahead of the plate edges (x = 0.0719), 9 mm above the top-plate level; the real bracket is not modelled.
CAM_POS = [0.078, 0.0, 0.040]
CAM_RPY = [math.pi, -(math.pi / 2 + math.radians(CAM_UP_DEG)), 0.0]

NOT_MODELLED = "The printed nose bracket, M2.5 stand-offs, the camera's USB-C cable clamp and the regulator's solder joints are not modelled (~25 g in reality)."
PI_MASS = dict(value=0.046, unit="kg", fidelity="estimated", rationale="The Raspberry Pi 5 product brief publishes no mass; a bare Pi 5 board weighs about 45-50 g (retailer listings of 50-62 g include packaging), 46 g taken as in assemblies/turret.toml.")  # fmt: skip
REG_MASS = dict(value=0.003, unit="kg", fidelity="datasheet", src="https://www.pololu.com/product/2851/specs", quote='Size: 0.7" x 0.8" x 0.35" Weight: 3.0 g')  # fmt: skip


HEADER = """# Skydio-style autonomous quadrotor (examples/skydio/): assemblies/x500v2.toml + Intel RealSense D435i on the nose (10 deg up) + Raspberry Pi 5 + Pololu
# D24V50F5 5 V regulator. GENERATED by `python examples/skydio/build_design.py` (the design API; Design.save keeps no comments), so edit that script, not this
# file. Frame, propulsion, power and avionics are x500v2.toml unchanged (its header documents the frame, motor order and every estimate). Added here:
#   cam  (group sensing)  free-placed on the nose, optical axis 10 deg above the airframe x axis; `depth` = the rangefinder device on the optical frame
#   pi   (group compute)  stacked 62 mm above the bottom-plate plane over the Pixhawk (on 18 mm stand-offs, not modelled); MAVLink to the FC on TELEM2
#   reg  (group compute)  5 V / 5 A step-down from a tap on PDB output 1; load_compute = Pi 5 full load + D435i max, on the battery side
# Not modelled: nose bracket, stand-offs, cable clamps; the Pi's heatsink / active cooler.
"""


def est(v, why, unit="m"):
    return dict(value=v, unit=unit, fidelity="estimated", rationale=why)


def main(out):
    d = Design.open(REPO / "assemblies" / "x500v2.toml")
    d.asm.doc["assembly"].update(
        name="skydio",
        description="Skydio-style vision-only autonomous quadrotor: Holybro X500 V2 (Pixhawk 6C, 4S 5200 mAh) + Intel RealSense D435i depth camera on the nose "
        "(tilted up 10 deg) + Raspberry Pi 5 companion computer + Pololu D24V50F5 5 V regulator. " + NOT_MODELLED,
    )  # fmt: skip
    step = lambda what, r: print(
        f"{what}: new {[f['code'] for f in r.new]} resolved {[f['code'] for f in r.resolved]}"
    )
    step(
        "camera",
        d.add(
            "intel-realsense-d435i", id="cam", pos=CAM_POS, rpy=CAM_RPY, group="sensing"
        ),
    )
    step(
        "pi",
        d.add(
            "raspberry-pi-5",
            id="pi",
            pos=[0.0, 0.0, 0.062],
            rpy=[0.0, 0.0, 0.0],
            group="compute",
        ),
    )
    step("pi mass", d.set("pi", "mass", **PI_MASS))
    step(
        "reg",
        d.add(
            "pololu-d24v50f5",
            id="reg",
            pos=[0.0, -0.055, 0.031],
            rpy=[0.0, 0.0, 0.0],
            group="compute",
        ),
    )
    step("reg mass", d.set("reg", "mass", **REG_MASS))

    # Wiring. The ports do not fit `autowire` (ESC pigtail XT30 -> solder pads, USB-C PD, USB-A to USB-C, 40-pin header -> JST-GH), so each cable is a plain wire
    # between the two ports with an estimated length (straight distance + slack).
    w = "awg-18-silicone-wire"  # the thinnest wire part in the library stands in for the small-gauge power / USB / UART leads
    step("reg input", d.wire("pdb.out1", "reg.vin", w, est(0.15, "The regulator sits on the top plate 6 cm from the PDB; its input is soldered to a tap on the PDB XT30 output 1 pigtail ('XT30 plug for ESCs & peripherals', holybro-pdb-60a). 0.15 m = distance plus slack."), conductors=2, name="pdb-to-reg"))  # fmt: skip
    step("pi power", d.wire("reg.vout", "pi.power_in", w, est(0.12, "Regulator on the top plate, Pi 5 on stand-offs 3 cm above it, USB-C power input at the board edge: about 6 cm apart, 0.12 m with slack."), conductors=2, name="reg-to-pi"))  # fmt: skip
    step("cam usb", d.wire("pi.usb", "cam.usb", w, est(0.20, "Pi 5 USB 3.0 port to the D435i USB-C on the nose, about 10 cm apart in the airframe; 0.20 m with the service loop."), name="pi-to-cam"))  # fmt: skip
    step("fc uart", d.wire("pi.gpio_uart", "fc.telem2", w, est(0.15, "Pi 5 GPIO UART (TX / RX / GND) to the Pixhawk 6C TELEM2 (MAVLink companion link, PX4 docs): the two boards are stacked, 0.15 m with slack."), name="pi-to-fc"))  # fmt: skip

    # Devices. The depth camera is the bench's rangefinder on the D435i optical frame (assemblies/depth-bench.toml), at the bench's 160 x 90 sub-sample.
    step("depth map", d.device_map("d435i", {"fov_h": "fov_h", "fov_v": "fov_v", "min_range": "min_range", "max_range": "max_range", "sigma1": "rms_error_frac"}))  # fmt: skip
    grid = dict(
        n_h=dict(value=160, unit="px", fidelity="estimated", rationale="Sub-sample of the 1280 px depth width (every 8th pixel) to keep the CPU ray cast cheap; same field of view (assemblies/depth-bench.toml)."),
        n_v=dict(value=90, unit="px", fidelity="estimated", rationale="Sub-sample of the 720 px depth height (every 8th pixel)."),
        rate_hz=dict(value=25, unit="Hz", fidelity="estimated", rationale="25 frames per second: 40 ticks of the 1 ms step (the rate must be an integer number of ticks; the D435i streams 30 fps by default, a frame-rate choice)."),
        resolution=dict(value=0.001, unit="m", fidelity="estimated", rationale="Depth units 1 mm, the D400 default depth scale (0.001 m per unit)."),
    )  # fmt: skip
    step(
        "depth",
        d.bind(
            type="rangefinder",
            name="depth",
            instance="cam",
            site="cam",
            site_port="optical",
            map="d435i",
            set=grid,
        ),
    )
    # Compute load on the battery side of the regulator (constant-current sink at the regulator input node, as the avionics loads of x500v2.toml):
    # Pi 5 under stress-ng 9.8 W (part, measured) + D435i 5 V x 0.7 A (D400 datasheet Table 3-46: ICC max 700 mA) = 13.3 W, over the regulator efficiency
    # 0.85 (D24V50F5 datasheet minimum) and the nominal pack voltage 14.8 V.
    i_bat = (9.8 + 5.0 * 0.7) / (0.85 * 14.8)
    step("compute load", d.bind(type="load", name="load_compute", instance="reg", port="vin", set={"i0": dict(
        value=round(-i_bat, 4), unit="A", fidelity="derived",
        derivation=f"Pi 5 under full CPU load 9.8 W (raspberry-pi-5 power_stress_ng_8gb, measured) + D435i 5 V x 0.700 A = 3.5 W (D400 datasheet Table 3-46, Vision Processor D4 Board ICC max 700 mA, VCC 5.00 V nominal) = 13.3 W on the 5 V rail, over the regulator efficiency 0.85 (pololu-d24v50f5 efficiency_min) x 14.8 V nominal pack = {i_bat:.4f} A out of the battery. Worst case: a Pi doing perception and planning, the camera projector on.")}))  # fmt: skip

    d.save(out)
    text = Path(out).read_text()
    Path(out).write_text(HEADER + text)
    for f in d.check():
        print(f.severity, f.code, f.message[:160])


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else REPO / "assemblies" / "skydio.toml")
