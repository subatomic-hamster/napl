"""Builds assemblies/skydio-land.toml through the design API: assemblies/skydio.toml (X500 V2 + D435i + Raspberry Pi 5, examples/skydio/) plus what landing needs.

    python examples/skydio-land/build_design.py [out.toml]      # default assemblies/skydio-land.toml; run from the repo root with the project venv

Added to the Skydio design (each is one `Design` call, the DRC delta is printed; needs no kernel):
  lidar   Benewake TF-Luna single-point LiDAR on the underside of the bottom plate, looking straight down; powered from the 5 V regulator, I2C to the Pi 5 header.
          Device `lidar` = a 1 x 1 pinhole rangefinder of the part's 2 degree field (assemblies/hopper.toml has the same binding). It measures the height above the
          ground (the landing zone's flatness is built from it, land.py) and the sink rate through the last metres.
  rtk_kit ZED-F9P RTK rover board + multi-band patch antenna (a mass allowance on the Pi deck, behind the Pi) and the `rtk` GNSS device (the F9P chip, 10 Hz, centimetre
          class). RTK ROVER INPUT: the position fix lands here as `/devices/skydio_rtk` (lat / lon / alt / vel_ned). Corrections come from a base station
          (a fixed base on the ground pads; the moving-baseline base on a ship's deck, examples/ship, napl.cuas.relnav). The Skydio program fuses it as a position
          measurement in the open (land.py: `Eskf.update_position`); under the forest canopy it is off (no fix), as it is in reality.
Frame, propulsion, power, the Pi 5 and the D435i are skydio.toml unchanged. The result is committed as assemblies/skydio-land.toml (Design.save keeps no comments;
the header below is added back)."""

import sys
from pathlib import Path

from napl.design import Design

REPO = Path(__file__).resolve().parents[2]

# Lidar pose in the root (bottom plate) frame: 3 mm below the plate underside, ahead of the hanging battery (which spans x = +-0.067 m), pointing straight down
# (the part frame's +z is the viewing direction: Ry(pi) flips it, as the hopper's lidar).
LIDAR_POS = [0.082, 0.0, -0.004]
LIDAR_RPY = [0.0, 3.141592653589793, 0.0]
KIT_POS = [-0.062, 0.0, 0.074]  # behind the Pi on the stand-offs, over the top plate

HEADER = """# Skydio-style autonomous quadrotor that takes off AND LANDS (examples/skydio-land/): assemblies/skydio.toml (Holybro X500 V2 + RealSense D435i + Raspberry Pi 5 +
# Pololu D24V50F5) plus a downward TF-Luna single-point lidar and a ZED-F9P RTK rover (board + patch antenna). GENERATED by `python examples/skydio-land/build_design.py`
# (the design API; Design.save keeps no comments), so edit that script, not this file. Added here:
#   lidar    (group sensing)  TF-Luna under the plate's front edge looking down; 5 V from the regulator, I2C to the Pi 5 GPIO header; device `lidar` (1 x 1 rangefinder)
#   rtk_kit  (group compute)  ZED-F9P board + multi-band patch antenna allowance behind the Pi; device `rtk` (GNSS, F9P RTK accuracy) = the RTK rover input
# Not modelled: the lidar and RTK brackets, the antenna cable, the SMA connector, the F9P's USB lead to the Pi (power only: the board is fed from the same 5 V rail).
"""


def est(v, why, unit="m"):
    return dict(value=v, unit=unit, fidelity="estimated", rationale=why)


def main(out):
    d = Design.open(REPO / "assemblies" / "skydio.toml")
    d.asm.doc["assembly"].update(
        name="skydio-land",
        description="Skydio-style vision-only quadrotor with landing sensors: Holybro X500 V2 + RealSense D435i (nose, 10 deg up) + Raspberry Pi 5 + Pololu D24V50F5 "
        "regulator + downward Benewake TF-Luna lidar + u-blox ZED-F9P RTK rover. The brackets, the antenna cable and the lidar / RTK solder joints are not modelled (~20 g in reality).",
    )  # fmt: skip
    step = lambda what, r: print(
        f"{what}: new {[f['code'] for f in r.new]} resolved {[f['code'] for f in r.resolved]}"
    )
    w = "awg-26-silicone-wire"  # the lidar's leads: 26 AWG as the hopper's lidar supply

    step("lidar", d.add("benewake-tf-luna", id="lidar", pos=LIDAR_POS, rpy=LIDAR_RPY, group="sensing"))  # fmt: skip
    step("lidar mass", d.set("lidar", "mass", **est(0.005, "The datasheet gives 5 g as a maximum (parts/electronics/benewake-tf-luna mass_max); the part has no typical mass, so the maximum is used.", "kg")))  # fmt: skip
    step("lidar power", d.wire("reg.vout", "lidar.power_in", w, est(0.16, "Regulator on the top plate, around the plate edge to the lidar under the front edge: about 0.1 m, 0.16 m with slack.")))  # fmt: skip
    # UART mode (the part's CFG pin left open, 115200 baud): TXD to GPIO5 (UART2 RX, J8.29), RXD to GPIO4 (UART2 TX, J8.7). UART0 (GPIO14 / 15) is the MAVLink link to the flight controller.
    # Single-conductor leads given by pin (inst.CONN.PIN): the Pi's `gpio_uart` port lists only UART0's pins; the lidar's ground is its power lead's (pin C.4).
    lead = est(
        0.20,
        "TF-Luna 6-pin lead to the Pi 5 header: the board sits 0.07 m above the lidar, 0.20 m with the service loop.",
    )
    step(
        "lidar tx",
        d.wire("lidar.C.3", "pi.J8.29", w, lead, conductors=1, name="lidar-tx-to-pi"),
    )  # TXD -> GPIO5 (UART2 RX)
    step(
        "lidar rx",
        d.wire("lidar.C.2", "pi.J8.7", w, lead, conductors=1, name="lidar-rx-from-pi"),
    )  # RXD <- GPIO4 (UART2 TX)

    step("rtk kit", d.add("generic-avionics-harness", id="rtk_kit", pos=KIT_POS, rpy=[0.0, 0.0, 0.0], group="compute"))  # fmt: skip
    step("rtk kit mass", d.set("rtk_kit", "mass", **est(0.040, "ZED-F9P breakout board (~10 g) plus a multi-band patch antenna (~30 g) as the hopper's RTK allowance (assemblies/hopper.toml, harness: neither weighed); the x500's own M8N stays on its mast for the flight-controller side.", "kg")))  # fmt: skip
    d.add(
        "ublox-zed-f9p", id="rtk_chip", offboard=True
    )  # data-only instance (no body, no mass): the device binding reads its params

    # RTK rover device (the hopper's binding, assemblies/hopper.toml). The simulated receiver is always "fixed": the program decides where the fix is usable.
    d.device_map("f9p", {"vel_std": "velocity_accuracy"})
    rtk = dict(
        rate_hz=est(10.0, "ZED-F9P RTK navigation rate is up to 20 Hz (datasheet); 10 Hz taken (every 100th tick), a usual setting.", "Hz"),
        latency_s=est(0.1, "No part publishes the receiver's output latency; 0.1 s = one sample at 10 Hz.", "s"),
        lat0=est(47.3769, "Arbitrary simulation origin (the repo's test-model site); not a claim about where the vehicle flies.", "deg"),
        lon0=est(8.5417, "As lat0.", "deg"),
        alt0=est(0.0, "World z = 0 at sea level, matching the environment device's origin_alt; a scene at altitude sets this to its origin_alt.", "m"),
        horiz_std=est(0.02, "The ZED-F9P RTK accuracy is 0.01 m + 1 ppm CEP (parts/electronics/ublox-zed-f9p, datasheet, static); 0.02 m covers antenna motion, multipath and a float / fix mix in flight (no dynamic figure published).", "m"),
        vert_std=est(0.03, "1.5 x horiz_std, as assemblies/x500v2.toml (the part publishes no vertical figure).", "m"),
        corr_time_s=est(20.0, "Time constant of the slowly varying part of an RTK position error (atmospheric residual, multipath): tens of seconds; no source.", "s"),
        corr_frac=est(0.5, "Share of the position variance that is the Gauss-Markov part: half; no source.", "1"),
    )  # fmt: skip
    step(
        "rtk device",
        d.bind(
            type="gnss", name="rtk", instance="rtk_chip", site="fc", map="f9p", set=rtk
        ),
    )

    # The lidar device: a 1 x 1 pinhole rangefinder of the TF-Luna's 2 degree field, accuracy +-6 cm to 3 m and +-2 % beyond (taken as 2 sigma), reads 0 outside 0.2 - 8 m.
    d.device_map("tfluna", {"fov_h": "fov", "fov_v": "fov", "min_range": "range_min", "max_range": "range_max_90pct", "resolution": "resolution", "rate_hz": "frame_rate_default"})  # fmt: skip
    grid = dict(
        n_h=est(1, "Single-point sensor: a 1 x 1 grid.", "px"),
        n_v=est(1, "Single-point sensor: a 1 x 1 grid.", "px"),
        sigma0=dict(value=0.03, unit="m", fidelity="derived", derivation="Datasheet accuracy +-6 cm (S1 of benewake-tf-luna, 0.2-3 m) taken as the 2-sigma bound: sigma 0.03 m."),
        sigma1=dict(value=0.01, unit="1", fidelity="derived", derivation="Datasheet accuracy +-2 % beyond 3 m taken as the 2-sigma bound: sigma 1 % of the range."),
    )  # fmt: skip
    step("lidar device", d.bind(type="rangefinder", name="lidar", instance="lidar", site="lidar", map="tfluna", set=grid))  # fmt: skip

    # Compute-side load of the two additions on the battery side of the regulator is inside the Pi budget (13.3 W worst case in skydio.toml leaves the TF-Luna's 0.35 W and
    # the F9P's ~0.1 W inside the D24V50F5's 5 A; load_compute is not changed).
    d.save(out)
    text = Path(out).read_text()
    Path(out).write_text(HEADER + text)
    for f in d.check():
        print(f.severity, f.code, f.message[:200])


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else REPO / "assemblies" / "skydio-land.toml")
