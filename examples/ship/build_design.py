"""Builds assemblies/osv.toml through the design API: a 12.6 m offshore support vessel (crew-boat class, Damen FCS 1204 outer dimensions) with a marked helipad, an RTK
base station, a deck datalink radio, a motion sensor on the deck, navigation lights and two electric propellers.

    python examples/ship/build_design.py [out.toml]      # default assemblies/osv.toml; run from the repo root with the project venv

Every edit is one `Design` call (the same ops as the MCP `design_*` tools and the viewer); the DRC delta of each is printed. Needs no kernel.
The result is committed as assemblies/osv.toml (comments are not kept by `Design.save`; the header below is added back)."""

import math
import sys
import tomllib
from pathlib import Path

from napl.design import Design

REPO = Path(__file__).resolve().parents[2]
DECK = 1.7  # m, main deck above the keel (hull part `depth`)
RGB = dict(
    red=[0.85, 0.05, 0.05, 1.0],
    green=[0.05, 0.65, 0.15, 1.0],
    white=[0.92, 0.92, 0.9, 1.0],
)

HEADER = """# Offshore support vessel (OSV): a 12.6 m aluminium crew boat (outer dimensions of the Damen Fast Crew Supplier 1204, estimated underwater form and mass)
# with a 3 x 3 m marked helipad on the aft deck, GENERATED by `python examples/ship/build_design.py` (the design API; Design.save keeps no comments), so edit that
# script, not this file. Examples and references: examples/ship/README.md. Parts (parts/marine, parts/electronics):
#   hull        generic-osv-hull-1260        deep-V work boat hull (vessel device: buoyancy cells, Fossen damping, added mass, skegs), keel at z = 0, bow +x
#   house       generic-osv-deckhouse        3.6 x 2.8 x 2.1 m wheelhouse; batteries and electronics stand inside it on the main deck
#   pad         generic-helipad-deck-3m      helipad: a LANDING surface (contype 0 / conaffinity 1, ray group 3) with painted markings (render only)
#   drive1/2    torqeedo-deep-blue-50i-1200  2 x electric propulsion motors on the transom (port / starboard), propellers prop1/2 (generic-4blade-propeller-550)
#   ctrl1/2     torqeedo-deep-blue-50i-controller   traction inverters, each from its own Deep Blue Battery 40 (bat1/2, 352 V, 38 kWh)
#   fc, pi, sik Pixhawk 6C autopilot (heading / speed control, PWM throttles), Raspberry Pi 5 (DP-lite, deck datalink), SiK radio = the DECK DATALINK
#   gps         Holybro M8N GPS (+ compass)  the autopilot's navigation GNSS on the cabin roof
#   rtk_board, rtk_ant   SparkFun GPS-RTK-SMA (u-blox ZED-F9P) + u-blox ANN-MB-00 antenna at the mast top = the RTK BASE station for the landers' moving-base GNSS
#   mru         VectorNav VN-100 Rugged       deck motion sensor ("MRU") on the main deck near the centre of motion; heave comes from the base antenna
#   hbat, reg5, reg12   house battery 6S + 5 V regulator (avionics) + 12 V regulator (navigation lights); lights: masthead, port, starboard, stern
# FRAME. The hull's part frame is the vessel's body frame: origin mid-length on the centreline at the keel level, x forward, y to port, z up. Still water is at the sea device's
# `level` (world z = 0); the scene helper (python/napl/cuas/ship.py) lowers the vessel by its design draft. DRIVES: each propeller pushes forward (shaft +z = world -x, rotor dir = -1).
# NOT MODELLED: waterjets (the real boat plans at 35 kn on two Ultrajet 340; here two propellers at 0-8 kn), diesel engines, rudders, the transom bracket of the drives, cable glands.
"""


def est(v, why, unit="m"):
    return dict(value=v, unit=unit, fidelity="estimated", rationale=why)


def main(out):
    asv = tomllib.loads((REPO / "assemblies" / "asv.toml").read_text())
    d = Design.new(
        "osv",
        REPO / "parts",
        description="12.6 m offshore support vessel: aluminium crew-boat hull, 2 x Torqeedo Deep Blue 50i electric propellers, helipad, RTK base station, deck datalink, MRU, nav lights",
    )
    d.doc["assembly"].update(timestep=0.001, seed=21)
    step = lambda what, r: print(
        f"{what}: new {[f['code'] for f in r.new]} resolved {[f['code'] for f in r.resolved]}"
    )

    # ---- structure: hull, wheelhouse, helipad, motion sensor ----------------------------------------------------------------------------------
    d.add("generic-osv-hull-1260", id="hull", root=True, group="hull")
    step("house", d.add("generic-osv-deckhouse", id="house", to="hull.deckhouse_seat", port="base", group="hull", mate="hull--house"))  # fmt: skip
    step("pad", d.add("generic-helipad-deck-3m", id="pad", to="hull.pad_seat", port="base", group="deck", mate="hull--pad"))  # fmt: skip
    step("mru", d.add("vectornav-vn-100-rugged", id="mru", to="hull.mru_seat", port="base", group="sensing", mate="hull--mru"))  # fmt: skip

    # ---- propulsion: motor on the transom, propeller on its shaft (spin joint), inverter and battery on the deck ----------------------------------
    for k, (side, y) in enumerate((("port", 1), ("starboard", -1)), 1):
        d.add("torqeedo-deep-blue-50i-1200", id=f"drive{k}", to=f"hull.drive_{side}", port="base", group="propulsion", mate=f"hull--drive{k}")  # fmt: skip
        d.add("generic-4blade-propeller-550", id=f"prop{k}", to=f"drive{k}.shaft", port="hub", group="propulsion", mate=f"spin{k}", joint={"type": "hinge", "spin": True})  # fmt: skip
        d.add("torqeedo-deep-blue-50i-controller", id=f"ctrl{k}", pos=[-1.3, 0.9 * y, DECK + 0.001], rpy=[0, 0, 0], group="power")  # fmt: skip
        d.add("torqeedo-deep-blue-battery-40", id=f"bat{k}", pos=[1.8, 0.7 * y, DECK + 0.001], rpy=[0, 0, 0], group="power")  # fmt: skip

    # ---- avionics, house power, RTK base, lights (free-placed on the deck inside the wheelhouse / on its roof) -------------------------------------
    roof = DECK + 2.14
    items = [
        ("holybro-pixhawk-6c", "fc", [0.4, 1.0, DECK + 0.001], "avionics"),
        ("raspberry-pi-5", "pi", [0.4, 0.45, DECK + 0.001], "compute"),
        ("pololu-d24v50f5", "reg5", [0.4, -0.1, DECK + 0.004], "power"),  # on 3 mm standoffs: the wires leaving the underside pads must not graze the deck
        ("pololu-d24v10f12", "reg12", [0.4, -0.5, DECK + 0.004], "power"),
        ("holybro-sik-telemetry-radio-v3", "sik", [0.4, -1.0, DECK + 0.001], "avionics"),
        ("cnhl-6200mah-6s-90c-xt90", "hbat", [3.3, -0.1, DECK + 0.025], "power"),
        ("sparkfun-gps-rtk-sma-16481", "rtk_board", [3.0, 0.0, DECK + 0.001], "avionics"),
        ("holybro-m8n-gps", "gps", [1.0, 0.5, roof], "avionics"),
        ("aqua-signal-series-25-led-nav-light", "light_mast", [3.0, 0.0, roof], "lights"),
        ("aqua-signal-series-25-led-nav-light", "light_port", [2.6, 1.3, roof], "lights"),
        ("aqua-signal-series-25-led-nav-light", "light_stbd", [2.6, -1.3, roof], "lights"),
        ("aqua-signal-series-25-led-nav-light", "light_stern", [-6.1, 0.0, DECK + 0.001], "lights"),
    ]  # fmt: skip
    for part, iid, pos, grp in items:
        # the house battery's XT90 lead points aft, at the regulators it feeds (facing the front wall it had to U-turn round the pack)
        d.add(
            part,
            id=iid,
            pos=pos,
            rpy=[0, 0, math.pi if iid == "hbat" else 0],
            group=grp,
        )
    step("rtk antenna", d.add("ublox-ann-mb-00", id="rtk_ant", to="house.roof_seat", port="base", group="avionics", mate="house--rtk-ant"))  # fmt: skip
    for iid, c in (
        ("light_port", "red"),
        ("light_stbd", "green"),
        ("light_mast", "white"),
        ("light_stern", "white"),
    ):
        d.edit([{"op": "color", "id": iid, "rgba": RGB[c]}])
    # offboard chips the device bindings refer to
    for part, iid in (
        ("tdk-icm-42688-p", "icm"),
        ("isentek-ist8310", "mag_chip"),
        ("ublox-neo-m8n", "gnss_chip"),
        ("ublox-zed-f9p", "gnss_base_chip"),
    ):
        d.add(part, id=iid, offboard=True)  # fmt: skip
    # regulator masses (the pololu parts publish none; as the ASV)
    reg_mass = asv["instances"][[i["id"] for i in asv["instances"]].index("reg")][
        "params"
    ]["mass"]
    d.set("reg5", "mass", **reg_mass)
    d.set("reg12", "mass", **dict(reg_mass, value=0.0025, quote='Size: 0.7" x 0.8" x 0.35" Weight: 2.5 g (estimated from the D24V50F5 sibling)', fidelity="estimated", rationale="The D24V10F12 is the smaller sibling of the D24V50F5 (3.0 g); no weight on the product page, 2.5 g taken."))  # fmt: skip
    d.set(
        "pi",
        "mass",
        **asv["instances"][[i["id"] for i in asv["instances"]].index("pi")]["params"][
            "mass"
        ],
    )
    fc_inst = asv["instances"][[i["id"] for i in asv["instances"]].index("fc")][
        "params"
    ]
    for k, v in fc_inst.items():
        d.set("fc", k, **v)
    d.set("sik", "telem_cable_length", value=1.2, unit="m", fidelity="estimated", rationale="The SiK radio and the Pixhawk are 2.0 m apart across the cabin bulkhead (y = -1.0 and +1.0 m): the JST-GH cable (0.8 m in the ASV) is replaced by a 1.2 m run with slack.")  # fmt: skip

    # ---- wiring (pin level where the ports list pins) -------------------------------------------------------------------------------------------
    hv, sig = "awg-2-0-silicone-wire", "awg-18-silicone-wire"
    for k in (1, 2):
        y = 1 if k == 1 else -1
        d.wire(f"bat{k}.power_out", f"ctrl{k}.power_in", hv, est(5.5, f"Battery {k} is in the wheelhouse (x = 1.8 m), its inverter at x = -1.3 m on the aft deck: 3.1 m along the deck plus 2.4 m of routing and service loops.") , conductors=2, name=f"bat{k}-to-ctrl{k}")  # fmt: skip
        d.wire(f"ctrl{k}.motor_out", f"drive{k}.phase", hv, est(5.5, f"Inverter {k} at x = -1.3 m on the deck, the drive on the transom at x = -5.3 m, 0.32 m above the keel: 4 m along the deck, 1.4 m down the transom, 0.3 m slack."), conductors=3, name=f"ctrl{k}-to-drive{k}")  # fmt: skip
        d.wire(f"fc.pwm{k}", f"ctrl{k}.signal", sig, est(3.5, "Pixhawk on the cabin bulkhead (x = 0.4 m), inverter at x = -1.3 m, across the doorway: 1.7 m plus 1.8 m routing."), name=f"fc-pwm{k}", from_pins=[f"FMU_PWM.{1 + k}", "FMU_PWM.10"], to_pins=["CTL.1", "CTL.2"])  # fmt: skip
    d.wire("hbat.power_out", "reg5.vin", sig, est(1.5, "House pack at x = 3.3 m, 5 V regulator at x = 0.4 m, along the centre aisle: 2.9 m. Rating: 5 A at 25 V needs 14-16 AWG; the library's thinnest wire part is 18 AWG (16 A), used for the bookkeeping."), conductors=2, name="hbat-to-reg5")  # fmt: skip
    d.wire("reg5.vin", "reg12.vin", sig, est(0.5, "The 12 V regulator's input pads are soldered to the 5 V regulator's input pads 0.4 m away on the shelf (a parallel tap on the house pack's feed)."), conductors=2, name="reg5-to-reg12")  # fmt: skip
    d.wire("reg5.vout", "pi.power_in", sig, est(0.6, "Regulator and Pi are 0.55 m apart on the bulkhead shelf."), conductors=2, name="reg5-to-pi")  # fmt: skip
    d.wire("reg5.vout", "fc.power1", sig, est(1.5, "Regulator at y = -0.1 m, Pixhawk at y = 1.0 m on the same shelf: 1.1 m plus slack."), conductors=2, name="reg5-to-fc", from_pins=["IO.VOUT", "IO.GND2"], to_pins=["POWER1.1", "POWER1.5"])  # fmt: skip
    d.wire("reg5.vout", "mru.power_in", sig, est(3.0, "5 V lead from the shelf (x = 0.4 m) out of the aft door to the MRU on the deck (x = -0.6 m): 1.0 m plus 2 m of routing along the bulkhead."), conductors=2, name="reg5-to-mru", from_pins=["IO.VOUT", "IO.GND2"], to_pins=["J1.1", "J1.5"])  # fmt: skip
    for iid in ("light_mast", "light_port", "light_stbd", "light_stern"):
        d.wire("reg12.vout", f"{iid}.power_in", sig, est(8.0, "12 V distribution from the cabin shelf to the light (roof 3.8 m up, 3 m forward, or 6.5 m aft to the stern light), routed along the cabin wall and gunwale; the lights' own 3 m pigtails are inside their mass."), conductors=2, name=f"reg12-to-{iid}", included_in=iid)  # fmt: skip
    d.wire("gps.gps_out", "fc.gps1", sig, "gps.cable_length", name="gps-to-fc", included_in="gps")  # fmt: skip
    d.wire("sik.telem", "pi.j8", sig, "sik.telem_cable_length", name="sik-to-pi", from_pins=["TELEM.1", "TELEM.2", "TELEM.3", "TELEM.6"], to_pins=["J8.2", "J8.24", "J8.21", "J8.25"], included_in="sik")  # fmt: skip
    d.wire("pi.gpio_uart", "fc.telem2", sig, est(1.0, "Pi 5 UART header (TX / RX / GND) to the Pixhawk 6C TELEM2 (MAVLink companion link): 0.55 m apart on the shelf, 1.0 m with slack."), name="pi-to-fc", from_pins=["J8.8", "J8.10", "J8.6"], to_pins=["TELEM2.3", "TELEM2.2", "TELEM2.6"])  # fmt: skip
    d.wire("mru.uart", "pi.j8", sig, est(3.0, "MRU on the deck (x = -0.6 m) to the Pi on the cabin bulkhead (x = 0.4 m): 1.0 m plus 2 m of routing."), name="mru-to-pi", from_pins=["J1.8", "J1.9", "J1.5"], to_pins=["J8.29", "J8.7", "J8.39"])  # fmt: skip
    d.wire("rtk_board.usb", "pi.usb", sig, "rtk_board.cable_length", name="rtk-to-pi", from_pins=["USBC.A4", "USBC.A7", "USBC.A6", "USBC.A1"], to_pins=["USB1.1", "USB1.2", "USB1.3", "USB1.4"], included_in="rtk_board")  # fmt: skip
    d.wire("rtk_ant.rf", "rtk_board.antenna", sig, "rtk_ant.cable_length", name="ant-to-rtk", included_in="rtk_ant")  # fmt: skip

    # ---- device maps (from the ASV assembly where the part is the same) -------------------------------------------------------------------------
    am = asv["device_maps"]
    d.device_map("drive_esc", am["basic_esc_t200"])
    d.device_map("drive_prop", am["t200_prop"])
    d.device_map("pack", am["pack"])
    d.device_map("hull_hydro", am["hull_hydro"])
    d.device_map("icm42688", am["icm42688"])
    d.device_map("ist8310", am["ist8310"])
    d.device_map("m8n", am["m8n"])
    d.device_map("vn100", {"gyro.full_scale": "gyro_fs_max", "gyro.noise_density": "gyro_noise_density", "gyro.bits": "gyro_adc_bits", "accel.full_scale": "accel_fs_max", "accel.noise_density": "accel_noise_density", "accel.bits": "accel_adc_bits"})  # fmt: skip
    d.device_map("f9p", {"vel_std": "velocity_accuracy"})
    dev = {x["name"]: x for x in asv["devices"]}

    # ---- devices -------------------------------------------------------------------------------------------------------------------------------------
    sea = dict(dev["sea"])
    sea["set"] = dict(sea["set"], rho=dict(value=1025.0, unit="kg/m^3", fidelity="estimated", rationale="Sea water (35 psu, 15 degC): 1025 kg/m3, the figure the hull's displacement and design draft use."))  # fmt: skip
    d.bind(**sea)
    d.bind(
        type="vessel",
        name="vessel",
        instance="hull",
        body="hull",
        map="hull_hydro",
        heading_frame=True,
    )
    for k in (1, 2):
        d.bind(type="battery", name=f"battery{k}", instance=f"bat{k}", port="power_out", ocv="lipo-cell-ocv-chen2006", map="pack")  # fmt: skip
        d.bind(type="esc", name=f"esc{k}", instance=f"ctrl{k}", port="power_in", motor=f"drive{k}", joint=f"spin{k}", map="drive_esc", bidirectional=True)  # fmt: skip
        d.bind(type="rotor", name=f"rotor{k}", instance=f"prop{k}", body=f"prop{k}", joint=f"spin{k}", map="drive_prop", dir=-1, water=True)  # fmt: skip
    d.bind(type="battery", name="battery_house", instance="hbat", port="power_out", ocv="lipo-cell-ocv-chen2006", map="pack")  # fmt: skip
    i5 = (9.8 + 1.5 + 1.0 + 0.2 + 0.7 + 0.5) / (0.85 * 22.2)
    d.bind(type="load", name="load_avionics", instance="reg5", port="vin", set={"i0": dict(value=round(-i5, 3), unit="A", fidelity="derived", derivation=f"Pi 5 under full CPU load 9.8 W (raspberry-pi-5 power_stress_ng_8gb, measured) + Pixhawk 6C 1.5 W + SiK radio 1.0 W (100 mW transmit, estimated) + VN-100 5 V x 40 mA = 0.2 W (datasheet) + SparkFun ZED-F9P board 5 V x 130 mA = 0.65 W (datasheet maximum) + M8N GNSS 0.5 W (estimated) = 13.7 W on the 5 V rail, over the regulator efficiency 0.85 (pololu-d24v50f5 efficiency_min) x 22.2 V nominal 6S pack = {i5:.3f} A (a constant-current sink).")})  # fmt: skip
    i12 = 4 * 1.0 / (0.85 * 22.2)
    d.bind(type="load", name="load_lights", instance="reg12", port="vin", set={"i0": dict(value=round(-i12, 3), unit="A", fidelity="derived", derivation=f"4 navigation lights x 1 W (aqua-signal-series-25-led-nav-light, estimated) = 4 W on the 12 V rail over a regulator efficiency of 0.85 (assumed as the 5 V part) x 22.2 V = {i12:.3f} A.")})  # fmt: skip
    d.bind(**dev["imu"])
    d.bind(**dev["mag"])
    d.bind(**dev["gnss"])
    d.bind(type="imu", name="mru_imu", instance="mru", site="mru", map="vn100", set={"rate_hz": est(250.0, "Simulation tick 1 ms (shared with the hopper / Skydio landers of ship_scene), so 250 Hz is every 4th tick, inside the VN-100's 400 Hz attitude / 800 Hz IMU rates (S1). The MRU's own AHRS filter is not simulated: napl.cuas.relnav.DeckLink adds the datasheet attitude accuracy (0.5 deg static, 1 deg dynamic) to the true attitude.", "Hz")})  # fmt: skip
    gb = dict(dev["gnss"]["set"])
    gb.update(
        rate_hz=est(10.0, "ZED-F9P-02B moving-base navigation rate 10 Hz (data sheet Table 5: 8 Hz with GPS+GLO+GAL+BDS, 10 Hz with fewer constellations; the 1 ms tick needs a divisor of 1000).", "Hz"),
        latency_s=est(0.1, "One sample at 10 Hz (the receiver's output latency is unpublished).", "s"),
        horiz_std=est(1.27, "STAND-ALONE (uncorrected) horizontal accuracy of the base: PVT 1.5 m CEP (data sheet Table 3) / 1.1774 = 1.27 m per coordinate. The base's absolute position is that of an ordinary receiver; only the RELATIVE position to a rover is centimetre-level (napl.cuas.relnav.RelGnss).", "m"),
        vert_std=est(1.9, "1.5 x horiz_std, as the ASV's GNSS.", "m"),
        vel_std=est(0.05, "ZED-F9P velocity accuracy 0.05 m/s (data sheet Table 1).", "m/s"),
    )  # fmt: skip
    d.bind(type="gnss", name="gnss_base", instance="gnss_base_chip", site="rtk_ant", set=gb)  # fmt: skip

    d.save(out)
    text = Path(out).read_text()
    Path(out).write_text(HEADER + text)
    for f in d.check():
        print(f.severity, f.code, f.message[:200])


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else REPO / "assemblies" / "osv.toml")
