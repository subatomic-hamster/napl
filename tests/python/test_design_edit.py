@needs_kernel
def test_simulate_hover_stock_x500(x500, tmp_path):
    r = x500.simulate("hover", out=tmp_path)
    print({k: v for k, v in r.items() if k != "calibration"})
    assert r["pass"], r
    assert r["altitude_error_max_m"] < 0.3 and abs(r["altitude_mean_m"] - 2.0) < 0.3
    assert 0.3 < r["hover_throttle"] < 0.8 and 5 < r["hover_current_A"] < 25
    assert r["endurance_s"] > 300 and r["soc_slope_per_s"] > 0


@needs_kernel
def test_simulate_hold_stock_arm(so101, tmp_path):
    r = so101.simulate("hold", out=tmp_path)
    print({k: v for k, v in r.items() if k != "servos"})
    assert r["pass"] and r["sag_max_rad"] < 0.1 and r["current_max_A"] > 0
    with pytest.raises(DesignError, match="no servo"):
        Design.open(X500, PARTS).simulate("hold", out=tmp_path)


@needs_kernel
def test_simulate_hover_without_thrust_margin_fails_cleanly(x500, tmp_path):
    x500.set(
        "bottom",
        "mass",
        value=5.0,
        unit="kg",
        fidelity="estimated",
        rationale="test: a 5 kg plate, T/W < 1",
    )
    r = x500.simulate("hover", out=tmp_path)
    assert (
        r["pass"] is False
        and "cannot hover" in r["reason"]
        and r["thrust_to_weight"] < 1.05
    )


