def test_edit_is_atomic(x500, docs):
    ops = [
        {
            "op": "set",
            "id": "mot1",
            "param": "mass",
            "value": 0.07,
            "unit": "kg",
            "fidelity": "estimated",
            "rationale": "test",
        },
        {"op": "swap", "id": "mot2", "part": MOTOR_VARIANT},
        {"op": "remove", "id": "no-such-instance"},
    ]
    with pytest.raises(DesignError, match="unknown instance"):
        x500.edit(ops)
    assert x500.doc == docs["x500"]
    with pytest.raises(DesignError, match="unknown op"):
        x500.edit([{"op": "explode"}])


# ---- swap, undo, DRC delta ---------------------------------------------------------------------------------------------------
def test_swap_motors_keeps_mates_wires_names_and_reports_the_drc_delta(x500, docs):
    r = x500.edit(
        [{"op": "swap", "id": ["mot1", "mot2", "mot3", "mot4"], "part": MOTOR_VARIANT}]
    )
    assert len(r.changes) == 4
    for ch in r.changes:
        assert [m["how"] for m in ch["mates"]["kept"]] == [
            "same port name"
        ] * 2  # motorN and spinN
        assert (
            not ch["mates"]["lost"] and not ch["wires"]["lost"] and not ch["dangling"]
        )
    names = [m.get("name", f"{m['a']}--{m['b']}") for m in x500.doc["mates"]]
    assert names == [
        m.get("name", f"{m['a']}--{m['b']}") for m in docs["x500"]["mates"]
    ]  # joint names unchanged
    assert {i["part"] for i in x500.doc["instances"] if i["id"].startswith("mot")} == {
        MOTOR_VARIANT
    }
    assert r.after["error"] == 0
    # 4 x 8 g heavier: the DRC messages that quote the weight change (before / after are both in the delta)
    assert any(c["after"]["code"] == "THRUST_TO_WEIGHT" for c in r.changed)
    # undo / redo walk the same stack
    x500.undo()
    assert x500.doc == docs["x500"]
    r2 = x500.redo()
    assert {i["part"] for i in x500.doc["instances"] if i["id"].startswith("mot")} == {
        MOTOR_VARIANT
    }
    assert r2.after == r.after
    with pytest.raises(DesignError, match="nothing to redo"):
        x500.redo()


def test_swap_to_a_motor_with_another_shaft_reports_what_it_loses(x500):
    r = x500.swap("mot1", "iflight-xing2-2207-1855kv")
    ch = r.changes[0]
    assert [m["mate"] for m in ch["mates"]["kept"]] == ["motor1"] and [
        m["mate"] for m in ch["mates"]["lost"]
    ] == ["spin1"]
    text = " ".join(ch["dangling"])
    assert (
        "esc1" in text
        and "spin1" in text
        and "j_rotor_bell" in text
        and "cable_length" in text
    )
    assert "FLOATING_INSTANCE" in codes(r.new, "error")  # prop1 lost its mate
    # the missing param can be supplied with provenance, as the numbers rule requires
    r = x500.set(
        "mot1",
        "j_rotor_bell",
        value=2e-6,
        unit="kg*m^2",
        fidelity="estimated",
        rationale="test: 5 mm bell, no datasheet",
    )
    assert r.changes[0]["note"].startswith("part iflight")


def test_swap_to_a_pack_without_rails_loses_the_battery_mates(x500):
    r = x500.swap("bat", "tattu-650mah-3s-75c-xt30")
    assert sorted(m["mate"] for m in r.changes[0]["mates"]["lost"]) == [
        "battery-l",
        "battery-r",
    ]
    assert "FLOATING_INSTANCE" in codes(r.new, "error")


def test_swap_to_a_tiny_pack_trips_the_battery_rules(x500):
    r = x500.swap("bat", PACK_VARIANT)
    assert not r.changes[0]["mates"]["lost"] and not r.changes[0]["dangling"]
    assert "BATTERY_C_RATING" in codes(r.new, "error")
    ft = next(c for c in r.changed if c["after"]["code"] == "FLIGHT_TIME")
    assert (
        "20.0 min" in ft["before"]["message"]
        and "min" in ft["after"]["message"]
        and ft["after"] != ft["before"]
    )
    assert r.after["error"] > r.before["error"]


def test_set_payload_on_the_arm_changes_servo_findings(so101, docs):
    base = {f.code: f for f in so101.findings()}
    pay = next(
        i for i in so101.build()["report"]["instances"] if i["id"] == "moving_jaw"
    )["mass"]
    r = so101.set(
        "moving_jaw",
        "mass",
        value=pay + 0.3,
        unit="kg",
        fidelity="estimated",
        rationale="test payload 0.3 kg held in the gripper",
    )
    assert r.changes[0]["unit"] == "kg"
    changed = {c["after"]["code"] for c in r.changed} | codes(r.new)
    assert "SERVO_TORQUE" in changed and "PAYLOAD_LIMIT" in changed
    assert base["PAYLOAD_LIMIT"].severity == "info"
    assert any(
        f["code"] == "PAYLOAD_LIMIT" and f["severity"] == "warning"
        for f in r.new + [c["after"] for c in r.changed]
    )
    st = [c for c in r.changed if c["after"]["code"] == "SERVO_TORQUE"]
    assert st and all(c["before"]["message"] != c["after"]["message"] for c in st)
    so101.undo()
    assert so101.doc == docs["so101"]


