def test_suggest_ranks_the_stock_part_first_for_its_own_port(x500):
    rows = x500.suggest("con1.motor", limit=20)
    assert rows[0]["part"] == "holybro-2216-kv920" and rows[0]["port"] == "base"
    assert "stock part (currently on this port)" in rows[0]["why"]
    ids = [r["part"] for r in rows]
    assert MOTOR_VARIANT in ids and "iflight-xing2-2207-1855kv" in ids
    assert [r["score"] for r in rows] == sorted(
        (r["score"] for r in rows), reverse=True
    )
    assert all(r["port"] for r in rows)
    # the arm connector (same category as the port's owner) is a legal but unlikely partner: not on top
    assert ids.index("holybro-x500v2-arm-connectors") > ids.index(
        "iflight-xing2-2207-2755kv"
    )
    assert x500.suggest("bat.power_out", limit=3)[0][
        "why"
    ]  # a power port: ranked by type / gender / rating


def test_suggest_power_port_penalises_insufficient_ratings(x500):
    rows = x500.suggest("pdb.out1", limit=200)  # xt30 outputs, 16.8 V source side
    flagged = [r for r in rows if any("below" in w for w in r["why"])]
    clean = [
        r
        for r in rows
        if not any("below" in w for w in r["why"]) and r["category"] == "esc"
    ]
    assert rows and clean
    assert all(r["score"] < min(c["score"] for c in clean) for r in flagged)


def test_suggest_swap_ranks_by_fit(x500):
    rows = x500.suggest("mot1", limit=5)
    assert rows[0]["part"] == MOTOR_VARIANT  # all ports kept, nothing dangling
    assert (
        rows[0]["mates_kept"] == 2
        and not rows[0]["mates_lost"]
        and not rows[0]["dangling"]
    )
    assert rows[0]["mass_delta"] == pytest.approx(0.008)
    worse = next(r for r in rows if r["part"] == "iflight-xing2-2207-1855kv")
    assert (
        worse["mates_lost"] == ["spin1"]
        and worse["dangling"]
        and "thrust_test" not in worse["missing_tables"]
    )
    packs = x500.suggest("bat", limit=40)
    assert packs[0]["part"] == PACK_VARIANT and not packs[0]["mates_lost"]
    # a real pack without rails ranks below the one that keeps its mates
    assert packs[[p["part"] for p in packs].index("tattu-650mah-3s-75c-xt30")][
        "mates_lost"
    ]


